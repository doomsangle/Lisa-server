# 纯 bash 补丁工具：在第 N 行之后插入多行内容
# =====================================================
_insert_after_line() {
    local file="$1" match_line="$2" patch_text="$3" tmp="${1}.patch.$$"
    awk -v needle="$match_line" -v patch="$patch_text" '
    { print }
    $0 ~ needle { print patch }
    ' "$file" > "$tmp" && mv -f "$tmp" "$file"
}

